 *
 * Every symbol is weak: a typed implementation in nvrm_os.c replaces it.
 * The RM core is NOT activated while any placeholder remains reachable.
 * Returning zero is intentionally not treated as readiness; the offline audit
 * counts strong implementations and keeps USB imaging forbidden.
 */
.section .text

.macro NVRM_WEAK name
.weak \name
.type \name,@function
\name:
    xor %eax, %eax
    ret
.size \name, .-\name
.endm

